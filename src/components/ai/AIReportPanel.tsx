import { Download, FileText, Printer, RefreshCw, Sparkles } from "lucide-react";
import { Card } from "@/components/ui/Card";
import { AIMarkdownContent } from "@/components/ai/AIMarkdownContent";
import { printHtmlContent } from "@/lib/utils/print";

interface AIReportPanelProps {
  title: string;
  content: string;
  subtitle?: string;
  onRegenerate?: () => void;
  isRegenerating?: boolean;
}

function downloadTextFile(filename: string, text: string) {
  const blob = new Blob([text], { type: "text/plain;charset=utf-8" });
  const url = URL.createObjectURL(blob);
  const anchor = document.createElement("a");
  anchor.href = url;
  anchor.download = filename;
  anchor.click();
  URL.revokeObjectURL(url);
}

function stripMarkdown(text: string): string {
  return text
    .replace(/^##+\s+/gm, "")
    .replace(/\*\*([^*]+)\*\*/g, "$1")
    .replace(/^-\s+/gm, "• ");
}

export function AIReportPanel({
  title,
  content,
  subtitle,
  onRegenerate,
  isRegenerating = false,
}: AIReportPanelProps) {
  function handlePrint() {
    const plain = stripMarkdown(content)
      .replace(/&/g, "&amp;")
      .replace(/</g, "&lt;")
      .replace(/>/g, "&gt;")
      .replace(/\n/g, "<br/>");
    printHtmlContent(title, plain);
  }

  function handleExport() {
    const safeName = title.replace(/[^\w\s-]/g, "").trim().replace(/\s+/g, "-") || "ai-report";
    downloadTextFile(`${safeName}.txt`, `${title}\n\n${stripMarkdown(content)}`);
  }

  return (
    <Card className="flex flex-col gap-4 rounded-3xl border-0 p-5 shadow-sm lg:p-6">
      <div className="flex flex-wrap items-center justify-between gap-3">
        <div className="flex items-center gap-2">
          <FileText className="size-5 text-[#2b7fff]" />
          <div>
            <span className="font-bold text-portal-heading">{title}</span>
            {subtitle && <p className="text-xs text-portal-muted">{subtitle}</p>}
          </div>
        </div>
        <div className="flex items-center gap-2">
          <button
            type="button"
            onClick={handleExport}
            className="flex size-9 items-center justify-center rounded-lg bg-portal-muted text-portal-muted hover:text-portal-heading"
            title="Download as text file"
          >
            <Download className="size-4" />
          </button>
          <button
            type="button"
            onClick={handlePrint}
            className="flex size-9 items-center justify-center rounded-lg bg-portal-muted text-portal-muted hover:text-portal-heading"
            title="Print report"
          >
            <Printer className="size-4" />
          </button>
        </div>
      </div>

      {onRegenerate ? (
        <button
          type="button"
          onClick={onRegenerate}
          disabled={isRegenerating}
          className="flex items-center justify-center gap-2 rounded-xl border border-[#C4922B]/40 bg-[#C4922B]/10 px-4 py-2.5 text-sm font-medium text-[#C4922B] transition hover:bg-[#C4922B]/15 disabled:opacity-60"
        >
          <RefreshCw className={`size-4 ${isRegenerating ? "animate-spin" : ""}`} />
          {isRegenerating ? "Regenerating…" : "Regenerate report"}
        </button>
      ) : null}

      <div className="rounded-2xl bg-portal-muted p-4 text-sm lg:p-5">
        <AIMarkdownContent content={content} />
      </div>

      <div className="flex items-center gap-2 rounded-xl bg-[#03214F] px-4 py-3">
        <Sparkles className="size-4 shrink-0 text-[#C4922B]" />
        <span className="text-xs text-white/80">Generated by Al Bayaan AI · English</span>
      </div>
    </Card>
  );
}
